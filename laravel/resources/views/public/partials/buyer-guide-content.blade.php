GARANTIE COMMERCIALE OVANIE
Version applicable aux achats effectués sur OVANIE
Chez OVANIE, la satisfaction et la confiance de nos clients constituent une priorité. La présente Garantie Commerciale définit les engagements pris par OVANIE afin d'assurer la qualité des produits et services proposés sur la plateforme.
1. OBJET DE LA GARANTIE
La Garantie Commerciale OVANIE vise à protéger l'acheteur contre :
•	La non-réception de la commande dans les conditions convenues ; 
•	La réception d'un produit différent de celui commandé ; 
•	La réception d'un produit endommagé avant la livraison ; 
•	Les défauts apparents constatés lors de la réception ; 
•	Les erreurs de quantité ou de référence imputables au vendeur ou au transporteur. 
Cette garantie s'ajoute aux garanties légales applicables dans le pays de livraison et ne les remplace pas.
2. PRODUITS COUVERTS
Sont couverts par la présente garantie :
•	Matériaux de construction ; 
•	Équipements électriques ; 
•	Produits de plomberie ; 
•	Outillages ; 
•	Équipements solaires ; 
•	Produits reconditionnés bénéficiant d'une garantie spécifique ; 
•	Produits importés vendus sur la plateforme ; 
•	Produits commercialisés par les vendeurs partenaires OVANIE. 
3. PRODUITS NON COUVERTS
La garantie ne s'applique pas :
•	Aux produits consommés après livraison ; 
•	Aux produits modifiés ou transformés par l'acheteur ; 
•	Aux dommages résultant d'une mauvaise utilisation ; 
•	Aux dégâts causés après la livraison ; 
•	Aux produits vendus comme occasion sans garantie ; 
•	Aux produits spéciaux tels que sable, gravier, latérite, terre, remblais, ciment déjà livré et accepté ; 
•	Aux cartes cadeaux, cartes rechargeables et bons d'achat déjà utilisés. 

4. CONTRÔLE À LA LIVRAISON
L'acheteur est invité à vérifier immédiatement :
•	La conformité du produit ; 
•	L'état général du colis ; 
•	Les quantités livrées ; 
•	Les références commandées. 
En cas d'anomalie, l'acheteur doit :
1.	Signaler le problème au livreur ; 
2.	Prendre des photographies ; 
3.	Déposer une réclamation depuis son compte client OVANIE dans un délai maximum de 72 heures. 
5. GARANTIE "PRODUIT CONFORME OU REMBOURSÉ"
Lorsque l'enquête confirme que :
•	Le produit reçu est différent de celui commandé ; 
•	Le produit présente un défaut avant utilisation ; 
•	Une erreur de préparation de commande est constatée ; 
OVANIE pourra, selon le cas :
•	Remplacer gratuitement le produit ; 
•	Procéder à un échange ; 
•	Effectuer un remboursement total ou partiel ; 
•	Attribuer un bon d'achat compensatoire. 

6. GARANTIE DE LIVRAISON
OVANIE s'engage à :
•	Confier les livraisons à des transporteurs qualifiés ; 
•	Assurer le suivi de la commande ; 
•	Informer le client des étapes de livraison ; 
•	Fournir une assistance en cas d'incident. 
Lorsque le retard est imputable à OVANIE ou au transporteur partenaire, une compensation commerciale pourra être accordée sous forme de bon d'achat.

7. GARANTIE SUR LES PRODUITS RECONDITIONNÉS
Les produits reconditionnés bénéficient d'une garantie spécifique indiquée sur leur fiche produit.
Cette garantie couvre :
•	Les défauts techniques non causés par l'utilisateur ; 
•	Les dysfonctionnements constatés dans la période de garantie. 
La durée de garantie est précisée avant l'achat.

8. GARANTIE SUR LES PRODUITS IMPORTÉS
Les produits expédiés depuis l'étranger bénéficient :
•	D'un contrôle de conformité avant expédition lorsque cela est possible ; 
•	D'un suivi logistique ; 
•	D'une assistance client dédiée. 
Les délais de livraison peuvent varier selon les formalités douanières et les contraintes internationales.

9. PROCÉDURE DE RÉCLAMATION
Pour bénéficier de la garantie commerciale, le client doit :
Étape 1 : Déclarer le problème
Depuis son compte client ou le Centre d'Assistance OVANIE.
Étape 2 : Fournir les justificatifs
•	Numéro de commande ; 
•	Photos ou vidéos ; 
•	Description du problème. 
Étape 3 : Analyse du dossier
OVANIE étudie la réclamation avec le vendeur concerné.
Étape 4 : Décision
Le client reçoit une réponse indiquant :
•	Le remplacement ; 
•	L'échange ; 
•	Le remboursement ; 
•	L'attribution d'un bon d'achat ; 
•	Ou le rejet motivé de la demande. 

10. DÉLAI DE TRAITEMENT
Les réclamations sont généralement traitées dans un délai de :
•	24 à 72 heures pour l'accusé de réception ; 
•	7 à 14 jours ouvrables pour la résolution complète du dossier. 
Des délais supplémentaires peuvent être nécessaires pour certains produits importés.

11. LIMITATION DE RESPONSABILITÉ
OVANIE ne saurait être tenue responsable :
•	Des dommages indirects ; 
•	De l'utilisation non conforme des produits ; 
•	Des retards dus à un cas de force majeure ; 
•	Des informations erronées fournies par l'acheteur ; 
•	Des incidents survenus après acceptation définitive de la livraison. 

12. ENGAGEMENT DE CONFIANCE OVANIE
OVANIE s'engage à :
✓ Sélectionner des vendeurs sérieux et vérifiés.
✓ Assurer un suivi transparent des commandes.
✓ Offrir un service client réactif.
✓ Faciliter les échanges entre acheteurs et vendeurs.
✓ Mettre tout en œuvre pour garantir une expérience d'achat fiable, sécurisée et professionnelle.

